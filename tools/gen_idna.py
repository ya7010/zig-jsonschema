#!/usr/bin/env python3
"""Generates src/idna_data.zig: IDNA2008 derived properties (RFC 5892),
Bidi classes (for the RFC 5893 Bidi rule) and virama code points, used by
the `hostname` / `idn-hostname` format checks.

Usage: python3 tools/gen_idna.py > src/idna_data.zig && zig fmt src/idna_data.zig
"""
import sys
import unicodedata as ud

# RFC 5892 section 2.6 (F): exceptions.
EXC_PVALID = {0x00DF, 0x03C2, 0x06FD, 0x06FE, 0x0F0B, 0x3007}
EXC_CONTEXTO = {0x00B7, 0x0375, 0x05F3, 0x05F4, 0x30FB} | set(range(0x0660, 0x066A)) | set(range(0x06F0, 0x06FA))
EXC_DISALLOWED = {0x0640, 0x07FA, 0x302E, 0x302F, 0x3031, 0x3032, 0x3033, 0x3034, 0x3035, 0x303B}

# Default_Ignorable_Code_Point (DerivedCoreProperties.txt).
DEFAULT_IGNORABLE = [
    (0x00AD, 0x00AD), (0x034F, 0x034F), (0x061C, 0x061C), (0x115F, 0x1160),
    (0x17B4, 0x17B5), (0x180B, 0x180F), (0x200B, 0x200F), (0x202A, 0x202E),
    (0x2060, 0x206F), (0x3164, 0x3164), (0xFE00, 0xFE0F), (0xFEFF, 0xFEFF),
    (0xFFA0, 0xFFA0), (0xFFF0, 0xFFF8), (0x1BCA0, 0x1BCA3), (0x1D173, 0x1D17A),
    (0xE0000, 0xE0FFF),
]
WHITE_SPACE = [(0x09, 0x0D), (0x20, 0x20), (0x85, 0x85), (0xA0, 0xA0), (0x1680, 0x1680),
               (0x2000, 0x200A), (0x2028, 0x2029), (0x202F, 0x202F), (0x205F, 0x205F), (0x3000, 0x3000)]
IGNORABLE_BLOCKS = [(0x20D0, 0x20FF), (0x1D100, 0x1D1FF), (0x1D200, 0x1D24F)]
OLD_HANGUL_JAMO = [(0x1100, 0x11FF), (0xA960, 0xA97F), (0xD7B0, 0xD7FF)]


def in_ranges(cp, ranges):
    return any(lo <= cp <= hi for lo, hi in ranges)


def is_noncharacter(cp):
    return (0xFDD0 <= cp <= 0xFDEF) or (cp & 0xFFFE) == 0xFFFE


def derived(cp):
    ch = chr(cp)
    if cp in EXC_PVALID:
        return "PVALID"
    if cp in EXC_CONTEXTO:
        return "CONTEXTO"
    if cp in EXC_DISALLOWED:
        return "DISALLOWED"
    gc = ud.category(ch)
    if gc == "Cn" and not is_noncharacter(cp):
        return "UNASSIGNED"
    if ch in "-0123456789abcdefghijklmnopqrstuvwxyz":
        return "PVALID"
    if cp in (0x200C, 0x200D):
        return "CONTEXTJ"
    if 0xD800 <= cp <= 0xDFFF:
        return "DISALLOWED"
    if ud.normalize("NFKC", ud.normalize("NFKC", ch).casefold()) != ch:
        return "DISALLOWED"
    if in_ranges(cp, DEFAULT_IGNORABLE) or in_ranges(cp, WHITE_SPACE) or is_noncharacter(cp):
        return "DISALLOWED"
    if in_ranges(cp, IGNORABLE_BLOCKS) or in_ranges(cp, OLD_HANGUL_JAMO):
        return "DISALLOWED"
    if gc in ("Ll", "Lu", "Lo", "Nd", "Lm", "Mn", "Mc"):
        return "PVALID"
    return "DISALLOWED"


def ranges_where(pred):
    out = []
    start = None
    for cp in range(0x110000):
        if pred(cp):
            if start is None:
                start = cp
        elif start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def write_table(out, name, ranges):
    out.write(f"pub const {name} = [_]Range{{\n")
    line = "   "
    for lo, hi in ranges:
        item = f" .{{ .lo = 0x{lo:X}, .hi = 0x{hi:X} }},"
        if len(line) + len(item) > 100:
            out.write(line + "\n")
            line = "   "
        line += item
    out.write(line + "\n};\n\n")


props = [derived(cp) for cp in range(0x110000)]
bidi = [ud.bidirectional(chr(cp)) for cp in range(0x110000)]

out = sys.stdout
out.write("//! Generated by tools/gen_idna.py from Python's unicodedata "
          f"(Unicode {ud.unidata_version}). Do not edit.\n\n")
out.write("pub const Range = @import(\"unicode_data.zig\").Range;\n\n")
write_table(out, "pvalid", ranges_where(lambda cp: props[cp] == "PVALID"))
write_table(out, "contexto", ranges_where(lambda cp: props[cp] == "CONTEXTO"))
write_table(out, "virama", ranges_where(lambda cp: ud.combining(chr(cp)) == 9))
for cls in ["R", "AL", "AN", "EN", "ES", "CS", "ET", "ON", "BN", "NSM", "L"]:
    write_table(out, f"bidi_{cls}", ranges_where(lambda cp, c=cls: bidi[cp] == c))
