#!/usr/bin/env python3
"""Generates src/unicode_data.zig: Unicode General_Category range tables
used by the regex engine for \\p{...} / \\P{...} escapes.

Usage: python3 tools/gen_unicode.py > src/unicode_data.zig && zig fmt src/unicode_data.zig
"""
import sys
import unicodedata

cats = {}
prev = None
start = 0
for cp in range(0x110000):
    c = unicodedata.category(chr(cp))
    if c != prev:
        if prev is not None:
            cats.setdefault(prev, []).append((start, cp - 1))
        prev = c
        start = cp
cats.setdefault(prev, []).append((start, 0x10FFFF))

out = sys.stdout
out.write("//! Generated by tools/gen_unicode.py from Python's unicodedata "
          f"(Unicode {unicodedata.unidata_version}). Do not edit.\n\n")
out.write("pub const Range = struct { lo: u21, hi: u21 };\n\n")
for name in sorted(cats):
    rs = cats[name]
    out.write(f"pub const {name} = [_]Range{{\n")
    line = "   "
    for lo, hi in rs:
        item = f" .{{ .lo = 0x{lo:X}, .hi = 0x{hi:X} }},"
        if len(line) + len(item) > 100:
            out.write(line + "\n")
            line = "   "
        line += item
    out.write(line + "\n};\n\n")
out.write("pub const categories = [_]struct { name: []const u8, ranges: []const Range }{\n")
for name in sorted(cats):
    out.write(f'    .{{ .name = "{name}", .ranges = &{name} }},\n')
out.write("};\n")
